"""Generate engine/src/data.rs from data/map.json and data/cards.json."""
import json, sys
R = sys.argv[1] if len(sys.argv) > 1 else '.'
m = json.load(open(f'{R}/data/map.json')); cards = json.load(open(f'{R}/data/cards.json'))
C = m['countries']; names = sorted(C, key=lambda n: (['Europe','Asia','Middle East','Africa','Central America','South America'].index(C[n]['region']), n))
idx = {n: i for i, n in enumerate(names)}
REG = {'Europe': 0, 'Asia': 1, 'Middle East': 2, 'Africa': 3, 'Central America': 4, 'South America': 5}
out = ['// Generated by scripts/gen_data.py — do not edit.', 'use crate::types::*;', f'pub const NC: usize = {len(names)};']
out.append('pub static COUNTRIES: [Country; NC] = [')
for n in names:
    c = C[n]
    adj = [idx[a] for a in c['adj'] if a in idx]
    adj_us = 'U.S.A.' in c['adj']; adj_su = 'U.S.S.R.' in c['adj']
    ee = 'Eastern Europe' in c['sub']; we = 'Western Europe' in c['sub']; sea = 'Southeast Asia' in c['sub']
    out.append(f'  Country {{ name: "{n}", region: {REG[c["region"]]}, ee: {str(ee).lower()}, we: {str(we).lower()}, sea: {str(sea).lower()}, stab: {c["stab"]}, bg: {str(c["bg"]).lower()}, adj_us: {str(adj_us).lower()}, adj_ussr: {str(adj_su).lower()}, adj: &{adj} }},')
out.append('];')
out.append('pub static CARDS: [CardInfo; 111] = [')
out.append('  CardInfo { id: 0, name: "-", ops: 0, era: 0, side: 0, star: false, scoring: false },')
for i in range(1, 111):
    c = cards[str(i)]
    era = {'Early': 0, 'Mid': 1, 'Late': 2}[c['era']]; side = {'Both': 0, 'US': 1, 'USSR': 2}[c['side']]
    nm = c['title'].replace('"', "'").replace('“', "'").replace('”', "'")
    out.append(f'  CardInfo {{ id: {i}, name: "{nm}", ops: {c["ops"]}, era: {era}, side: {side}, star: {str(c["star"]).lower()}, scoring: {str(c["scoring"]).lower()} }},')
out.append('];')
for n in names:
    const = n.upper().replace('.', '').replace('/', '_').replace(' ', '_').replace("'", '')
    out.append(f'pub const {const}: usize = {idx[n]};')
open(f'{R}/engine/src/data.rs', 'w').write('\n'.join(out) + '\n')
print('countries', len(names))
